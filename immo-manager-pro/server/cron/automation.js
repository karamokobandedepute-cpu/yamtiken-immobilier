/**
 * Génère automatiquement les relances pour les loyers en retard
 * Exécution: Tous les jours à 9h00
 */
export const autoGenerateRelances = async () => {
  console.log('🤖 [AUTO] Génération automatique des relances...')
  
  try {
    // Trouver les baux avec loyers en retard
    const bauxEnRetard = await prisma.lease.findMany({
      where: {
        statut: 'ACTIF',
        payments: {
          none: {
            datePaiement: {
              gte: new Date(new Date().setDate(1)) // Depuis début mois
            }
          }
        }
      },
      include: {
        client: true,
        unite: { include: { building: true } }
      }
    })
    
    let created = 0
    
    for (const bail of bauxEnRetard) {
      // Vérifier si une relance existe déjà pour ce mois
      const existingRelance = await prisma.relance.findFirst({
        where: {
          bailId: bail.id,
          dateRelance: {
            gte: new Date(new Date().setDate(1))
          }
        }
      })
      
      if (!existingRelance) {
        // Créer la relance automatique
        await prisma.relance.create({
          data: {
            bailId: bail.id,
            clientId: bail.clientId,
            type: 'LOYER',
            montantDu: bail.loyerMensuel,
            dateRelance: new Date(),
            statut: 'EN_ATTENTE',
            priorite: calculatePriority(bail),
            messageAuto: generateRelanceMessage(bail),
            autoGenerated: true
          }
        })
        created++
      }
    }
    
    console.log(`✅ [AUTO] ${created} relances générées`)
    return { success: true, count: created }
  } catch (error) {
    console.error('❌ [AUTO] Erreur génération relances:', error)
    return { success: false, error: error.message }
  }
}

/**
 * Envoie automatiquement les relances par email/SMS
 * Exécution: Tous les jours à 10h00
 */
export const autoSendRelances = async () => {
  console.log('🤖 [AUTO] Envoi automatique des relances...')
  
  try {
    const relances = await prisma.relance.findMany({
      where: {
        statut: 'EN_ATTENTE',
        autoGenerated: true,
        dateEnvoi: null
      },
      include: {
        client: true,
        bail: { include: { unite: { include: { building: true } } } }
      },
      take: 50 // Limiter à 50 par batch
    })
    
    let sent = 0
    
    for (const relance of relances) {
      try {
        // Envoyer email
        await sendEmail({
          to: relance.client.email,
          subject: `Relance loyer - ${relance.bail.unite.building.nom}`,
          template: 'relance',
          data: {
            client: relance.client,
            bail: relance.bail,
            montant: relance.montantDu,
            dateLimite: getDateLimite()
          }
        })
        
        // Marquer comme envoyé
        await prisma.relance.update({
          where: { id: relance.id },
          data: {
            dateEnvoi: new Date(),
            canal: 'EMAIL'
          }
        })
        
        sent++
      } catch (err) {
        console.error(`❌ [AUTO] Erreur envoi relance ${relance.id}:`, err)
      }
    }
    
    console.log(`✅ [AUTO] ${sent} relances envoyées`)
    return { success: true, count: sent }
  } catch (error) {
    console.error('❌ [AUTO] Erreur envoi relances:', error)
    return { success: false, error: error.message }
  }
}

