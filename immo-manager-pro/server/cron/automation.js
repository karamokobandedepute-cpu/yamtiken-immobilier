/**
 * Analyse les données et génère des recommandations
 * Exécution: Quotidienne
 */
export const generateAIRecommendations = async () => {
  console.log('🧠 [IA] Génération recommandations intelligentes...')
  
  try {
    const recommendations = []
    
    // 1. Recommandation: Augmenter loyer sur unités sous-evaluées
    const unitesSousEvaluees = await prisma.unite.findMany({
      where: {
        statut: 'OCCUPE',
        loyer: {
          lt: prisma.unite.aggregate({
            where: { buildingId: { equals: prisma.unite.fields.buildingId } },
            _avg: { loyer: true }
          })._avg.loyer * 0.8
        }
      },
      include: { building: true }
    })
    
    if (unitesSousEvaluees.length > 0) {
      recommendations.push({
        type: 'PRICING',
        priority: 'HAUTE',
        title: 'Unités sous-évaluées détectées',
        description: `${unitesSousEvaluees.length} unités ont un loyer inférieur à 80% de la moyenne de l'immeuble`,
        action: 'ReviewPricing',
        potentialGain: calculatePotentialGain(unitesSousEvaluees),
        entities: unitesSousEvaluees.map(u => ({ id: u.id, type: 'UNITE' }))
      })
    }
    
    // 2. Recommandation: Relance proactive clients à risque
    const clientsRisque = await prisma.client.findMany({
      where: {
        leases: {
          some: {
            statut: 'ACTIF',
            payments: {
              none: {
                datePaiement: {
                  gte: new Date(Date.now() - 45 * 24 * 60 * 60 * 1000)
                }
              }
            }
          }
        }
      }
    })
    
    if (clientsRisque.length > 0) {
      recommendations.push({
        type: 'RECOUVREMENT',
        priority: 'CRITIQUE',
        title: 'Clients à risque détectés',
        description: `${clientsRisque.length} clients n'ont pas payé depuis 45+ jours`,
        action: 'ImmediateRecovery',
        entities: clientsRisque.map(c => ({ id: c.id, type: 'CLIENT' }))
      })
    }
    
    // 3. Recommandation: Optimisation occupation
    const statsOccupation = await getOccupationStats()
    if (statsOccupation.taux < 85) {
      recommendations.push({
        type: 'MARKETING',
        priority: 'MOYENNE',
        title: 'Taux d\'occupation faible',
        description: `Taux actuel: ${statsOccupation.taux}%. Objectif: 90%`,
        action: 'LaunchMarketingCampaign',
        potentialGain: statsOccupation.potentielManque * 12 // Annuel
      })
    }
    
    // Sauvegarder les recommandations
    for (const rec of recommendations) {
      await prisma.recommendation.upsert({
        where: {
          id: `${rec.type}_${new Date().toISOString().slice(0, 10)}`
        },
        update: rec,
        create: {
          id: `${rec.type}_${new Date().toISOString().slice(0, 10)}`,
          ...rec,
          dateCreated: new Date(),
          status: 'PENDING'
        }
      })
    }
    
    console.log(`🧠 [IA] ${recommendations.length} recommandations générées`)
    return { success: true, recommendations }
  } catch (error) {
    console.error('❌ [IA] Erreur génération recommandations:', error)
    return { success: false, error: error.message }
  }
}

