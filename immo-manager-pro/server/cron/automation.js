// HELPERS
// ============================================

const calculatePriority = (bail) => {
  const joursRetard = new Date().getDate() - 5 // Assume échéance le 5
  if (joursRetard > 20) return 'CRITIQUE'
  if (joursRetard > 10) return 'HAUTE'
  return 'MOYENNE'
}

const generateRelanceMessage = (bail) => {
  return `Cher ${bail.client.prenom},\n\n` +
    `Nous constatons que votre loyer pour l'unité ${bail.unite.nom} ` +
    `n'a pas été réglé pour ce mois.\n\n` +
    `Montant dû: ${bail.loyerMensuel.toLocaleString()} FCFA\n` +
    `Merci de régulariser votre situation dans les plus brefs délais.`
}

const getDateLimite = () => {
  const date = new Date()
  date.setDate(date.getDate() + 7)
  return date.toLocaleDateString('fr-FR')
}

const generateWeeklyReport = async () => {
  // Implémentation simplifiée
  return { pdf: Buffer.from('PDF content'), data: {} }
}

const calculatePotentialGain = (unites) => {
  return unites.reduce((sum, u) => sum + (u.loyer * 0.2), 0) // 20% augmentation
}

const getOccupationStats = async () => {
  const total = await prisma.unite.count()
  const occupees = await prisma.unite.count({ where: { statut: 'OCCUPE' } })
  const vacantes = total - occupees
  
  const loyerMoyen = await prisma.unite.aggregate({
    where: { statut: 'OCCUPE' },
    _avg: { loyer: true }
  })
  
  return {
    taux: Math.round((occupees / total) * 100),
    potentielManque: vacantes * (loyerMoyen._avg.loyer || 0)
  }
}

