/**
 * Détecte et crée les alertes automatiques
 * Exécution: Toutes les heures
 */
export const autoDetectAlerts = async () => {
  console.log('🤖 [AUTO] Détection alertes...')
  
  const alerts = []
  
  try {
    // 1. Alertes contrats expirant (moins de 30 jours)
    const contratsExpirant = await prisma.lease.findMany({
      where: {
        statut: 'ACTIF',
        dateFin: {
          lte: new Date(Date.now() + 30 * 24 * 60 * 60 * 1000),
          gte: new Date()
        }
      },
      include: { client: true, unite: { include: { building: true } } }
    })
    
    for (const contrat of contratsExpirant) {
      const daysLeft = Math.ceil((contrat.dateFin - new Date()) / (1000 * 60 * 60 * 24))
      alerts.push({
        type: 'CONTRAT_EXPIRANT',
        severity: daysLeft <= 7 ? 'CRITIQUE' : daysLeft <= 15 ? 'HAUTE' : 'MOYENNE',
        message: `Contrat de ${contrat.client.nom} expire dans ${daysLeft} jours`,
        entityType: 'LEASE',
        entityId: contrat.id
      })
    }
    
    // 2. Alertes unités vacantes depuis plus de 30 jours
    const unitesVacantes = await prisma.unite.findMany({
      where: {
        statut: 'VACANT',
        updatedAt: {
          lte: new Date(Date.now() - 30 * 24 * 60 * 60 * 1000)
        }
      },
      include: { building: true }
    })
    
    for (const unite of unitesVacantes) {
      alerts.push({
        type: 'UNITE_VACANTE_LONGUE',
        severity: 'MOYENNE',
        message: `Unité ${unite.nom} vacante depuis plus de 30 jours`,
        entityType: 'UNITE',
        entityId: unite.id
      })
    }
    
    // 3. Alertes paiements en retard (plus de 10 jours)
    const paiementsRetard = await prisma.lease.findMany({
      where: {
        statut: 'ACTIF',
        dateDebut: {
          lte: new Date(new Date().setDate(1)) // Commencé avant ce mois
        }
      },
      include: {
        client: true,
        payments: {
          where: {
            datePaiement: {
              gte: new Date(new Date().setDate(1))
            }
          }
        }
      }
    })
    
    const bauxSansPaiement = paiementsRetard.filter(b => b.payments.length === 0)
    
    for (const bail of bauxSansPaiement) {
      alerts.push({
        type: 'LOYER_NON_PAYE',
        severity: 'HAUTE',
        message: `Loyer non payé pour ${bail.client.nom}`,
        entityType: 'LEASE',
        entityId: bail.id
      })
    }
    
    // Créer les alertes en base
    let created = 0
    for (const alert of alerts) {
      const existing = await prisma.alerte.findFirst({
        where: {
          type: alert.type,
          entityId: alert.entityId,
          statut: { not: 'RESOLUE' }
        }
      })
      
      if (!existing) {
        await prisma.alerte.create({
          data: {
            ...alert,
            statut: 'NOUVELLE',
            autoGenerated: true
          }
        })
        created++
      }
    }
    
    console.log(`✅ [AUTO] ${created} alertes créées`)
    return { success: true, count: created, alerts }
  } catch (error) {
    console.error('❌ [AUTO] Erreur détection alertes:', error)
    return { success: false, error: error.message }
  }
}

