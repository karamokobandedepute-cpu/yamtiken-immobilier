/**
 * Génère et envoie les rapports automatiques
 * Exécution: Hebdomadaire (Lundi 8h)
 */
export const autoGenerateReports = async () => {
  console.log('🤖 [AUTO] Génération rapports automatiques...')
  
  try {
    // Rapport hebdomadaire
    const rapport = await generateWeeklyReport()
    
    // Envoyer aux administrateurs
    const admins = await prisma.user.findMany({
      where: { role: { in: ['ADMIN', 'SUPER_ADMIN', 'DIRECTION'] } }
    })
    
    for (const admin of admins) {
      await sendEmail({
        to: admin.email,
        subject: 'Rapport hebdomadaire - YAMTIKEN BEHEMOTH',
        template: 'report',
        attachments: [{ filename: 'rapport.pdf', content: rapport.pdf }]
      })
    }
    
    console.log(`✅ [AUTO] Rapport envoyé à ${admins.length} administrateurs`)
    return { success: true }
  } catch (error) {
    console.error('❌ [AUTO] Erreur génération rapport:', error)
    return { success: false, error: error.message }
  }
}

